    static RuleCatalog()
    {
        All = Build();
        ById = All.ToDictionary(r => r.Id, StringComparer.Ordinal);
        RunAlerts =
        [
            new("RUN-MASS-MISSING", "Many files disappeared", Severity.High, "A root that is online lost at least 20 % and at least 50 of its files since the previous run"),
