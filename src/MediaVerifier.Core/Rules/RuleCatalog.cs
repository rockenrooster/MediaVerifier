            new("RUN-READ-ERRORS", "Storage read errors", Severity.Critical, "Any GEN-UNREADABLE in the run; recommends checking the drive"),
        ];
    }

    public static IReadOnlyList<RuleDefinition> All { get; }

    public static IReadOnlyList<RunAlertDefinition> RunAlerts { get; }

    public static RuleDefinition Get(string id) =>
        ById.TryGetValue(id, out RuleDefinition? rule) ? rule : throw new KeyNotFoundException($"Unknown rule '{id}'.");

    public static bool TryGet(string id, out RuleDefinition rule) => ById.TryGetValue(id, out rule!);

