using System.Security.Cryptography;
using System.Text;
using MediaVerifier.Core.Updates;

namespace MediaVerifier.Tests.Updates;

/// <summary>Manifest signatures (subplan 14, tasks U-03 and U-10) with a throwaway key made in the test.</summary>
public sealed class UpdateTrustTests
{
    [Fact]
    public void A_signed_manifest_verifies_and_any_change_or_other_key_fails()
    {
        using RSA signer = RSA.Create(3072);
        using RSA other = RSA.Create(3072);
        string publicKey = signer.ExportSubjectPublicKeyInfoPem();
        byte[] manifest = Encoding.UTF8.GetBytes("{\"schemaVersion\":1,\"version\":\"0.1.0.2\",\"tag\":\"v0.1.0.2\"}");
        byte[] signature = signer.SignData(manifest, HashAlgorithmName.SHA256, RSASignaturePadding.Pkcs1);

        Assert.True(UpdateTrust.VerifyManifestSignature(manifest, signature, publicKey));

        byte[] tampered = [.. manifest];
        tampered[^3] ^= 1;
        Assert.False(UpdateTrust.VerifyManifestSignature(tampered, signature, publicKey));
        Assert.False(UpdateTrust.VerifyManifestSignature(manifest, signature, other.ExportSubjectPublicKeyInfoPem()));
        Assert.False(UpdateTrust.VerifyManifestSignature(manifest, signature, string.Empty));
        Assert.False(UpdateTrust.VerifyManifestSignature(manifest, signature, "not a key"));
    }

    [Fact]
    public void The_production_key_is_an_RSA_3072_public_key()
    {
        using RSA rsa = RSA.Create();
        rsa.ImportFromPem(UpdateTrust.PublicKeyPem);
        Assert.Equal(3072, rsa.KeySize);
        Assert.Throws<CryptographicException>(() => rsa.ExportRSAPrivateKey());
    }

    [Fact]
    public void A_signature_from_any_other_key_does_not_verify()
    {
        // The production key is generated by the owner (task U-01); the repository never holds a private key.
        using RSA signer = RSA.Create(3072);
        byte[] manifest = Encoding.UTF8.GetBytes("{}");
        byte[] signature = signer.SignData(manifest, HashAlgorithmName.SHA256, RSASignaturePadding.Pkcs1);
        Assert.False(UpdateTrust.VerifyManifestSignature(manifest, signature, UpdateTrust.PublicKeyPem));
    }
}

