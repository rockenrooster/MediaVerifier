<#
.SYNOPSIS
    Runs the performance suite and records the results (subplan 15, task T-11; subplan 16, task H-01).

.DESCRIPTION
    Builds Release, runs every test in the Perf category except the corruption benchmark (which has its own report,
    docs/detection-rates.md), and writes docs/perf-results.md: the machine, the date, and one row per measurement
    with its budget. A failing budget fails the run.

    The audio and frame-sampling tests need FFmpeg: the bundle, or MEDIAVERIFIER_FFMPEG_DIR, and a full FFmpeg on
    PATH for the generated fixtures (subplan 15). Without them those tests skip and their rows are missing.

.EXAMPLE
    .\scripts\Measure-Performance.ps1
#>
[CmdletBinding()]
param(
    [string] $Output = (Join-Path $PSScriptRoot '..\docs\perf-results.md')
)

$ErrorActionPreference = 'Stop'
$root = Resolve-Path (Join-Path $PSScriptRoot '..')
$rows = Join-Path ([IO.Path]::GetTempPath()) ("MediaVerifier-perf-" + [Guid]::NewGuid().ToString('N') + '.md')

dotnet build (Join-Path $root 'MediaVerifier.sln') -c Release --nologo -v quiet
if ($LASTEXITCODE -ne 0) { throw 'Build failed' }

$env:MEDIAVERIFIER_PERF_REPORT = $rows
try {
    # One test at a time: measurements taken side by side would compete for the same cores and disk.
    dotnet test (Join-Path $root 'MediaVerifier.sln') -c Release --no-build --nologo `
        --filter 'Category=Perf&FullyQualifiedName!~CorruptionBenchmark' `
        -- xUnit.ParallelizeTestCollections=false xUnit.MaxParallelThreads=1
    $testExit = $LASTEXITCODE
}
finally {
    Remove-Item Env:\MEDIAVERIFIER_PERF_REPORT -ErrorAction SilentlyContinue
}

$cpu = (Get-CimInstance Win32_Processor | Select-Object -First 1).Name.Trim()
$memory = [math]::Round((Get-CimInstance Win32_ComputerSystem).TotalPhysicalMemory / 1GB)
$os = (Get-CimInstance Win32_OperatingSystem)
$disk = (Get-PhysicalDisk | Where-Object { $_.DeviceId -eq '0' } | Select-Object -First 1)
$diskText = if ($disk) { "$($disk.FriendlyName) ($($disk.MediaType))" } else { 'unknown' }

$lines = @(
    '# Performance results',
    '',
    'Generated by `scripts/Measure-Performance.ps1` (tasks T-11 and H-01). Budgets are in the',
    '[master plan](../plans/00-master-plan.md); docs/perf.md explains the earlier measurements and findings.',
    '',
    "Date: $(Get-Date -Format 'yyyy-MM-dd'). Machine: $cpu, $memory GB RAM, $diskText, $($os.Caption) $($os.BuildNumber).",
    '',
    '| Measurement | Setup | Result | Budget |',
    '|-------------|-------|--------|--------|'
)
if (Test-Path $rows) {
    $lines += Get-Content $rows
    Remove-Item $rows
}

$lines += @(
    '',
    'Measured by hand on the release candidate (subplan 16, Performance pass), not by this script: cold start',
    '(the log line `First paint … after process start`), idle CPU and memory after visiting every page, and the',
    'installed size from `build.ps1`. See docs/test-procedures.md, procedure P-7.'
)
Set-Content -Path $Output -Value $lines -Encoding utf8
Write-Host "Wrote $Output"
if ($testExit -ne 0) { throw "A performance budget failed (dotnet test exit code $testExit)" }
